import os
import joblib
import pandas as pd
import numpy as np
 
class LivePopulationRiskEndpoint:
    def __init__(self):
        """
        Initialization Block: Instantly loads your pre-trained model blueprints
        and locks them into your laptop's memory for high-speed live lookups.
        """
        # Establish the parent directory paths relative to this file's position
        self.base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
        self.model_dir = os.path.join(self.base_dir, "models", "production")

        print("Initializing Affected Population Estimation Live Engin e Wrapper...")
        print("-> Loading heavy pre-trained models into memory via Virtual Storage Maps...")

        # Load the 3 binary portables generated by your serialization script
        self.mean_model = joblib.load(os.path.join(self.model_dir, "g_mu_bart_model.pkl"), mmap_mode='r')
        self.var_model = joblib.load(os.path.join(self.model_dir, "g_sigma_gbt_model.pkl"), mmap_mode='r')
        self.multiplier = joblib.load(os.path.join(self.model_dir, "calibrated_multiplier.pkl"))

        print(f" -> Success: Model weights active. Calibrated risk multiplier locked at: {self.multiplier:.4f}")

    def predict_realtime_demographics(self, input_precip_mm, flood_tiff_path=None):
        """
        Optimized Tabular Matrix Extraction using Raster Mask coordinates.
        Direct Pandas mapping over the 11-million-row matrix bypassing heavy GeoPandas joins.
        """
        import rasterio
        import time

        # 1. Establish path boundaries to your local 11-million row reference master file
        master_file = os.path.join(self.base_dir, "data", "processed", "master", "Final_Training_Dataset_Gampaha.csv")
        if not os.path.exists(master_file):
            print("❌ [Module 2 Error] Master reference dataset CSV file not found!")
            return {"status": "FAILED", "error": "Reference dataset missing"}

        if not flood_tiff_path or not os.path.exists(flood_tiff_path):
            # Fallback path if not provided
            flood_tiff_path = os.path.join(self.base_dir, "interface", "backend", "outputs", "flood_extent_4326.tiff")
            if not os.path.exists(flood_tiff_path):
                print("⚠️ [Module 2 Warning] Active flood raster file (.tif) not found yet.")
                return {"status": "EMPTY_INPUT", "error": "No flood raster found yet."}

        print("\n" + "─"*50)
        print("⚡ [Module 2] STARTING GEOSPATIAL VECTOR INFUSION")
        print("─"*50)

        start_time = time.time()

        # Step 1: Extract coordinates from Module 1 Raster Mask
        print("🔍 Step 1: Extracting coordinate vectors from Module 1 raster mask...")
        with rasterio.open(flood_tiff_path) as src:
            flood_band = src.read(1)
            rows, cols = np.where(flood_band == 255)
            x_coords, y_coords = rasterio.transform.xy(src.transform, rows, cols)

        print(f"   -> Found {len(x_coords):,} raw flooded pixels inside raster file.")
        if len(x_coords) == 0:
            print("✅ [Module 2] Processing halted: 0 flooded pixels detected.")
            return {"status": "SUCCESS", "demographic_data": []}

        # ====================================================================
        # CRITICAL PRECISION ALIGNMENT CORRECTION
        # Round both coordinate arrays to exactly 4 decimal places (~11 meters)
        # This ensures pixels snap together perfectly without dropping rows.
        # ====================================================================
        # Step 2: Build operational index dataframe
        df_flooded_pixels = pd.DataFrame({
            'Longitude': np.round(x_coords, 4),
            'Latitude': np.round(y_coords, 4)
        })
        # Remove duplicate grid cell entries within the same 11m block
        df_flooded_pixels.drop_duplicates(inplace=True)
        print(f"   -> Consolidated to {len(df_flooded_pixels):,} unique coordinates at 11m grid resolution.")

        # Step 3: Stream Ingestion via Chunking to prevent RAM Allocation Crashes
        print("📖 Step 2: Streaming reference baseline matrix arrays (Low-RAM Chunking)...")
        matched_chunks = []
        chunk_idx = 0
        total_rows_scanned = 0

        # We read 1 million rows at a time so your system never runs out of RAM
        for chunk in pd.read_csv(master_file, chunksize=1000000):
            chunk_idx += 1
            total_rows_scanned += len(chunk)

            chunk['Longitude'] = np.round(chunk['Longitude'], 4)
            chunk['Latitude'] = np.round(chunk['Latitude'], 4)

            # Match current chunk coordinates against flooded pixels
            merged_chunk = pd.merge(chunk, df_flooded_pixels, on=['Longitude', 'Latitude'], how='inner')
            if len(merged_chunk) > 0:
                matched_chunks.append(merged_chunk)

            print(f"   -> Scanned chunk {chunk_idx}: {total_rows_scanned:,} total rows evaluated...")

        if len(matched_chunks) == 0:
            print("⚠️ [Module 2 Warning] Coordinates matched 0 entries across all 11 million rows!")
            return {"status": "SUCCESS", "demographic_data": [], "note": "No coordinate overlapping found."}

        # Combine only the matched coordinates
        df_work = pd.concat(matched_chunks, ignore_index=True)
        print(f"🎯 Step 3: SUCCESS! Matched {len(df_work):,} rows within the active flood zone matrix.")

        # Print quick coordinate checkpoint summary directly to your console log
        print("\n📍 --- ACTIVE MATCHED COORDINATES CHECKPOINT ---")
        print(df_work[['Ds_Division_Name', 'Longitude', 'Latitude', 'Ghs_Pop_Baseline']].head(5).to_string(index=False))
        print("--------------------------------------------------")

        # Step 4: Run Machine Learning Models
        print("\n🔮 Step 4: Injecting rainfall context and generating predictions via .pkl engines...")
        df_work['Precip_Mm'] = input_precip_mm

        features = [
            'Ghs_Pop_Baseline', 'Ghs_Built_S_Total', 'Ghs_Built_S_NonRes', 'Ghs_Built_V_Total',
            'Ghs_Settlement_Type', 'Nightlight_Intensity', 'Precip_Mm', 'Is_Holiday', 'Is_Weekend',
            'Severity_Weight', 'Occupancy_Adj', 'Built_Up_Ratio', 'Weighted_Pop_Engineered', 'Ambient_Pop_Landscan'
        ]

        # Fill unexpected runtime missing features safely using local data properties
        for feat in features:
            if feat not in df_work.columns:
                df_work[feat] = 0.0
            df_work[feat] = df_work[feat].fillna(df_work[feat].median() if df_work[feat].median() == df_work[feat].median() else 0.0)

        X_live = df_work[features].values

        # 3. High-speed vector prediction via pre-loaded blueprints (No historical data reading needed)
        mu_log = self.mean_model.predict(X_live)
        log_var = self.var_model.predict(X_live)

        # Calculate localized uncertainty ranges across the grid cells
        sigma_log = np.sqrt(np.exp(np.clip(log_var, -10, 10)))
        upper_log = mu_log + (self.multiplier * sigma_log)

        # 4. Reverse the log-transformation safely to restore real-world counts
        raw_mean = np.maximum(0, np.expm1(mu_log))
        raw_upper = np.maximum(0, np.expm1(upper_log))

        # Apply the pixel capacity ceiling boundaries to avoid population leaks
        max_capacity = np.maximum(df_work['Ghs_Pop_Baseline'].values, df_work['Ambient_Pop_Landscan'].values)
        max_capacity = np.maximum(max_capacity, 1.0) # Baseline floor check

        df_work['Predicted_Mean_Affected'] = np.minimum(raw_mean, max_capacity)
        df_work['Predicted_Upper_Bound'] = np.minimum(raw_upper, max_capacity)

        # Ensure strings are stripped of spaces and title-cased for grouping matches
        df_work['Ds_Division_Name'] = df_work['Ds_Division_Name'].astype(str).str.strip().str.title()
        df_work['Ds_Division_Name'] = df_work['Ds_Division_Name'].str.replace('Jaela', 'Ja Ela', regex=False).str.replace('Ja-Ela', 'Ja Ela', regex=False)

        # Step 5: Divisional Aggregation
        print("📊 Step 5: Aggregating pixel predictions up to Divisional boundaries...")
        ds_predictions = df_work.groupby('Ds_Division_Name').agg(
            Predicted_Mean_Affected=('Predicted_Mean_Affected', 'sum'),
            Upper_Risk_Limit=('Predicted_Upper_Bound', 'sum')
        ).reset_index()

        print("\n📈 --- DYNAMIC PREDICTION OUTCOME PER DIVISION ---")
        print(ds_predictions.to_string(index=False))
        print("--------------------------------------------------")

