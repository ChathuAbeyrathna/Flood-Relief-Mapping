        final_output_list = []
        global_fallback = {"male": 0.49, "female": 0.51, "child": 0.22, "adult": 0.63, "elderly": 0.15}

        # 7. Apply demographic profiling over aggregated division sums
        for idx, row in ds_predictions.iterrows():
            d_name = row['Ds_Division_Name']
            ratios = demographic_ratios.get(d_name, global_fallback)

